/* The photographs migration, generated rather than typed.
   node tools/gen-photo-sql.mjs

   Same principle as tools/gen-seed-sql.mjs: 29 slots, each with a name, a
   label and a description already written down in two files that are generated
   themselves. Retyping them into SQL at the last step would put the
   transcription risk back exactly where it costs most — with the database as
   the new source of truth, so a typo becomes permanent.

   Reads tools/photo-slots.mjs for the slot, the label and whether it is
   decoration, and data/seed-photos.js for the description and the built-in
   file's dimensions. Writes the whole migration, hand-written parts included,
   so running it twice produces byte-identical SQL and the output is reviewable
   in a diff.

   The bucket and its policies are in the same file on purpose. A storage bucket
   whose size and type limits live somewhere else — a dashboard, a second
   migration, a README — is a bucket that gets recreated one day without them. */

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { runInNewContext } from "node:vm";
import { slotList } from "./photo-slots.mjs";

const OUT = "supabase/migrations/20260801000400_photos.sql";

function load(file, name) {
  const sandbox = {};
  runInNewContext(readFileSync(file, "utf8"), sandbox);
  if (!sandbox[name]) throw new Error(`${file} did not define ${name}`);
  return sandbox[name];
}

const SEED = load("data/seed-photos.js", "SEED_PHOTOS");
const SLOTS = slotList();

/* ── the two files have to describe the same 29 slots ─────────────────────
   A slot here with no seed entry would insert a row with no description. A
   seed entry with no slot here is a photograph the editor never lists. Both
   are silent; neither is allowed. */
{
  const inSql = new Set(SLOTS.map((s) => s.slot));
  const inSeed = new Set(Object.keys(SEED));
  const missing = [...inSeed].filter((s) => !inSql.has(s));
  const extra = [...inSql].filter((s) => !inSeed.has(s));
  if (missing.length || extra.length) {
    throw new Error(
      "tools/photo-slots.mjs and data/seed-photos.js disagree about which slots exist.\n" +
      (extra.length ? `  listed but not extracted: ${extra.join(", ")}\n` : "") +
      (missing.length ? `  extracted but not listed: ${missing.join(", ")}\n` : "") +
      "Run node tools/extract-photos.mjs after changing the slot table."
    );
  }
}

const q = (s) => (s === null || s === undefined ? "null" : `'${String(s).replace(/'/g, "''")}'`);
const n = (v) => (v === null || v === undefined ? "null" : String(v));

const rows = SLOTS.map((s, i) => {
  const seed = SEED[s.slot];
  const alt = s.decorative ? "" : (seed.alt || "");
  return `  (${q(s.slot)}, ${q(s.label)}, ${q(alt)}, ${s.decorative}, ` +
         `${n(seed.width)}, ${n(seed.height)}, ${(i + 1) * 10})`;
}).join(",\n");

const decorative = SLOTS.filter((s) => s.decorative).length;

const sql = `-- ============================================================================
-- Phase 6 — the photographs
--
-- Generated by tools/gen-photo-sql.mjs from tools/photo-slots.mjs and
-- data/seed-photos.js. Do not edit by hand; edit those and run it again.
--
-- Three things happen here, and the order matters:
--
--   1. photos gets an is_decorative column, and the alt rule is corrected
--   2. one row per slot, ${SLOTS.length} of them
--   3. the storage bucket the uploads go into, with its limits and policies
-- ============================================================================


-- ----------------------------------------------------------------------------
-- 1. Decoration is not a missing description
--
-- The original table said: a photograph with a file must have alt text. That is
-- right for a photograph and wrong for a backdrop. ${decorative} of the ${SLOTS.length} slots are
-- texture — behind a scrim, behind a gradient, aria-hidden, carrying alt="" on
-- purpose — and forcing a description onto those would make a screen reader
-- announce the wallpaper.
--
-- So the rule becomes: a photograph that is content and has a file must have a
-- description. Decoration is exempt, and which slots are decoration is the
-- markup's business rather than the owner's, which is why is_decorative is
-- protected by the trigger below rather than offered in the editor.
-- ----------------------------------------------------------------------------

alter table public.photos
  add column if not exists is_decorative boolean not null default false;

alter table public.photos drop constraint if exists photos_alt_required_with_image;
alter table public.photos add constraint photos_alt_required_with_image
  check (is_decorative or storage_path is null or length(btrim(alt)) > 0);

comment on column public.photos.is_decorative is
  'The image is texture, not content: aria-hidden, alt="" on purpose. Set by the markup, never by the editor.';


-- ----------------------------------------------------------------------------
-- 2. Only the photograph and its description are the owner's
--
-- Same reasoning as only_value_may_change() on site_copy: row level security
-- grants an UPDATE on a row, not on a column. Without this an editor could
-- rename a slot — and a renamed slot is a photograph that stops appearing on
-- the site, with no error anywhere to say why.
--
-- storage_path, source_path, alt, width and height are the owner's. slot,
-- label, is_decorative and sort_order describe where the picture goes, and
-- that is decided by the markup.
-- ----------------------------------------------------------------------------

create or replace function public.only_photo_may_change()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.id <> old.id or new.slot <> old.slot then
    raise exception 'The photograph slot "%" cannot be renamed or moved. Only the picture and its description can be changed.', old.slot;
  end if;
  new.label         = old.label;
  new.is_decorative = old.is_decorative;
  new.sort_order    = old.sort_order;
  return new;
end;
$$;

drop trigger if exists photos_photo_only on public.photos;
create trigger photos_photo_only
  before update on public.photos
  for each row execute function public.only_photo_may_change();

-- A described photograph needs its description. The CHECK above already refuses
-- it, but a CHECK constraint's message names a constraint, and the person
-- reading it is a café owner. This says the same thing in their language, and
-- tools/test-admin.mjs holds the editor to the identical sentence.
create or replace function public.check_photo_alt()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if not new.is_decorative and new.storage_path is not null
     and length(btrim(new.alt)) = 0 then
    raise exception 'The photograph "%" needs a short description of what is in it. It is what someone using a screen reader hears in place of the picture, and what shows if the image ever fails to load.', new.label;
  end if;
  return new;
end;
$$;

drop trigger if exists photos_alt_check on public.photos;
create trigger photos_alt_check
  before insert or update on public.photos
  for each row execute function public.check_photo_alt();


-- ----------------------------------------------------------------------------
-- 3. One row per slot
--
-- storage_path is null on every one of them, which is the whole design: null
-- means "the photograph the site shipped with", and that photograph is in the
-- markup rather than in a bucket. So this table starts out changing nothing,
-- and a project that has never had an upload renders exactly the site in git.
--
-- The descriptions are the ones already in the markup, so the editor opens
-- showing what is actually on the page rather than 24 empty boxes.
-- ----------------------------------------------------------------------------

insert into public.photos (slot, label, alt, is_decorative, width, height, sort_order) values
${rows}
on conflict (slot) do nothing;

do $$
declare n integer;
begin
  select count(*) into n from public.photos;
  if n <> ${SLOTS.length} then raise exception 'photos: expected ${SLOTS.length} rows, found %', n; end if;
end $$;


-- ============================================================================
-- 4. The bucket
--
-- file_size_limit and allowed_mime_types are set HERE, on the bucket, and not
-- only in the editor. The editor's checks are a courtesy that lets someone find
-- out before they wait for an upload; they are not a control. Anyone holding
-- the owner's token can post straight at the storage API and never load
-- admin.js at all. See memory.md, "Storage abuse".
--
-- public = true means /storage/v1/object/public/site-photos/… serves the file
-- without consulting row level security, which is what the site needs: a
-- visitor is not signed in. It does NOT make the bucket listable — that is the
-- select policy below, and it is deliberately restricted to the owner. A public
-- bucket with a select policy for anon is an enumerable bucket.
--
-- One bucket per feature, not one shared bucket. Uptown's reasoning, worth
-- keeping: share a bucket and one feature's orphan cleanup decides the fate of
-- another feature's files.
--
-- 3 MB is generous for a photograph that has already been resized to 2000px and
-- re-encoded as webp in the browser — a 2000px webp of a café interior is
-- usually under 400 KB. The headroom is for the original, which is kept
-- alongside so a crop can be undone, and which is whatever the camera or the
-- phone produced.
--
-- Three types, and no fourth. webp is what the editor writes; jpeg and png are
-- what an original arrives as. SVG is deliberately absent and must stay absent:
-- it is the one image format that can contain a script, and a public bucket
-- serving one from this project's own origin would run it there.
-- ============================================================================

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('site-photos', 'site-photos', true, 3145728,
        array['image/webp', 'image/jpeg', 'image/png'])
on conflict (id) do update set
  public            = excluded.public,
  file_size_limit   = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;


-- ---- policies on the objects themselves -------------------------------------
-- Writes are the allowlisted owner and nobody else — the same is_owner() every
-- content table uses, so there is one answer to "who may change this site" and
-- it is stored in one place.
--
-- The select policy is what makes the bucket *listable* through the API. The
-- owner needs it to see what is in there; anon does not, and granting it would
-- turn every uploaded file into something a stranger can enumerate even though
-- each individual URL is already public.

drop policy if exists "site-photos owner insert" on storage.objects;
create policy "site-photos owner insert"
  on storage.objects for insert to authenticated
  with check (bucket_id = 'site-photos' and public.is_owner());

drop policy if exists "site-photos owner update" on storage.objects;
create policy "site-photos owner update"
  on storage.objects for update to authenticated
  using (bucket_id = 'site-photos' and public.is_owner())
  with check (bucket_id = 'site-photos' and public.is_owner());

drop policy if exists "site-photos owner delete" on storage.objects;
create policy "site-photos owner delete"
  on storage.objects for delete to authenticated
  using (bucket_id = 'site-photos' and public.is_owner());

drop policy if exists "site-photos owner list" on storage.objects;
create policy "site-photos owner list"
  on storage.objects for select to authenticated
  using (bucket_id = 'site-photos' and public.is_owner());
`;

/* --check regenerates and compares rather than writing, so `npm test` fails
   when the slot table or a description has been changed and the migration was
   never regenerated. Without it the committed SQL and the site's own data drift
   apart quietly, and the drift only shows up on a project that is set up from
   scratch — which is the worst possible moment to find it. */
if (process.argv.includes("--check")) {
  const on_disk = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (on_disk === sql) {
    console.log(`  ok   the photographs migration matches the slots and the seed data`);
    process.exit(0);
  }
  console.log("  FAIL the photographs migration is not what the data would generate");
  console.log("         run: node tools/gen-photo-sql.mjs");
  process.exit(1);
}

writeFileSync(OUT, sql);
console.log(`${SLOTS.length} slots (${decorative} decorative) -> ${OUT}`);
